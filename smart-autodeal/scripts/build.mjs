// Concatenates src/frontend/*.js (in file-name order) into public/app.js.
// The frontend is plain browser JavaScript sharing one global scope, so ORDER MATTERS.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../src/frontend/', import.meta.url);
const files = readdirSync(dir).filter(f => f.endsWith('.js')).sort();
const out = '// AUTO-GENERATED by scripts/build.mjs – edit files in src/frontend/, not this file.\n' + files.map(f => readFileSync(new URL(f, dir), 'utf8')).join('');
writeFileSync(new URL('../public/app.js', import.meta.url), out);
console.log(`public/app.js built from ${files.length} files`);
